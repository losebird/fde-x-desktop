test('hallStamp changes after a pairing code is minted', () => {
  const source = readFileSync(clientPath, 'utf8')
  const stampSrc = source.slice(source.indexOf('function listOf('), source.indexOf('async function pullMailbox('))
  const hallStamp = new Function(stampSrc + '; return hallStamp')()
  const empty = { requests: [], peers: [], inbox: [], nudges: [] }
  const minted = { ...empty, pairCode: { code: '123456', remainMs: 9 * 60 * 1000 } }
  assert.notEqual(hallStamp(empty), hallStamp(minted))
  assert.match(hallStamp(minted), /123456/)
  const withSheet = { ...empty, pendingSheet: { kind: '工单', action: '现查', rows: [{ no: 'TK-1' }] } }
  assert.notEqual(hallStamp(empty), hallStamp(withSheet))
  assert.match(hallStamp(withSheet), /TK-1/)
})
